-- ── TICKET CLOSURES ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS ticket_closures (
  id             TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  ticket_id      TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  closed_by      TEXT,
  closed_by_name TEXT,
  client_called  BOOLEAN NOT NULL DEFAULT FALSE,
  satisfaction   TEXT CHECK (satisfaction IN ('satisfait', 'probleme-persistant', 'remarques')),
  comments       TEXT,
  closed_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ── DUTY SCHEDULE ────────────────────────────────────────────
-- week_start: Monday of the week (date only)
CREATE TABLE IF NOT EXISTS duty_schedule (
  id          TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  week_start  DATE NOT NULL,
  sector_id   TEXT NOT NULL REFERENCES sectors(id) ON DELETE CASCADE,
  slot_index  INTEGER NOT NULL CHECK (slot_index >= 0),
  employee_id TEXT REFERENCES employees(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (week_start, sector_id, slot_index)
);


-- ── NOTIFICATIONS ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS notifications (
  id         TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  user_id    TEXT NOT NULL,   -- mock user id (e.g. 'cgr-1')
  type       TEXT NOT NULL CHECK (type IN ('info', 'success', 'warning', 'danger')),
  title      TEXT NOT NULL,
  message    TEXT NOT NULL,
  ticket_id  TEXT REFERENCES tickets(id) ON DELETE SET NULL,
  read       BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);


-- ── MOCK USER ACCOUNTS (replaces mock-data/users.ts) ─────────
