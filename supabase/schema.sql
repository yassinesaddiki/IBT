-- ── EXTENSIONS ───────────────────────────────────────────────
CREATE EXTENSION IF NOT EXISTS "pgcrypto";


-- ── SECTORS ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS sectors (
  id         TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  name       TEXT UNIQUE NOT NULL,
  status     TEXT NOT NULL DEFAULT 'actif' CHECK (status IN ('actif', 'inactif')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);


-- ── CATEGORIES ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS categories (
  id         TEXT PRIMARY KEY,   -- ex: CAT-01
  label      TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sub_categories (
  id               TEXT PRIMARY KEY,   -- ex: COP-01
  category_id      TEXT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  label            TEXT NOT NULL,
  default_severity TEXT CHECK (default_severity IN ('Critique', 'Haute', 'Moyenne')),
  created_at       TIMESTAMPTZ DEFAULT NOW()
);


-- ── VEHICLES ─────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS vehicles (
  id            TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  plate         TEXT UNIQUE NOT NULL,          -- ex: DO 248
  brand         TEXT NOT NULL,                 -- ex: Dacia
  model         TEXT NOT NULL,                 -- ex: Sandero
  vehicle_type  TEXT NOT NULL DEFAULT 'voiture' CHECK (vehicle_type IN ('voiture', 'camion', 'nacelle', 'moto', 'autre')),
  assigned_team TEXT CHECK (assigned_team IN ('eep', 'sed', NULL)),
  status        TEXT NOT NULL DEFAULT 'actif' CHECK (status IN ('actif', 'inactif', 'maintenance')),
  created_at    TIMESTAMPTZ DEFAULT NOW()
);


-- ── EMPLOYEES ────────────────────────────────────────────────
-- matricule format: NNNNNL (5 digits + 1 uppercase letter), ex: 12345A
CREATE TABLE IF NOT EXISTS employees (
  id           TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  name         TEXT NOT NULL,
  initials     TEXT NOT NULL,
  role         TEXT NOT NULL CHECK (role IN ('eep', 'sed', 'cgr', 'coordinator', 'observer')),
  sector_id    TEXT REFERENCES sectors(id) ON DELETE SET NULL,
  phone        TEXT NOT NULL,
  email        TEXT UNIQUE NOT NULL,
  matricule    TEXT UNIQUE NOT NULL,            -- format: NNNNNL
  avatar_url   TEXT,                            -- Supabase Storage path or null
  vehicle_id   TEXT REFERENCES vehicles(id) ON DELETE SET NULL,
  status       TEXT NOT NULL DEFAULT 'actif' CHECK (status IN ('actif', 'inactif')),
  joined_date  DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at   TIMESTAMPTZ DEFAULT NOW()
);


-- ── TICKETS ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS tickets (
  id                   TEXT PRIMARY KEY,   -- format: IBT-YYMM-NNN (auto-generated by trigger)
  client_name          TEXT NOT NULL,
  contract_number      TEXT NOT NULL,
  phone                TEXT NOT NULL,
  address              TEXT NOT NULL,
  sector_id            TEXT REFERENCES sectors(id) ON DELETE SET NULL,
  sector_name          TEXT NOT NULL,      -- denormalized for display even if sector renamed
  category_id          TEXT REFERENCES categories(id) ON DELETE SET NULL,
  category_label       TEXT NOT NULL,
  sub_category_id      TEXT REFERENCES sub_categories(id) ON DELETE SET NULL,
  sub_category_label   TEXT NOT NULL,
  severity             TEXT NOT NULL CHECK (severity IN ('Critique', 'Haute', 'Moyenne')),
  description          TEXT,
  status               TEXT NOT NULL DEFAULT 'nouveau',
  created_by           TEXT,               -- mock user id (e.g. 'cgr-1')
  created_by_name      TEXT,
  pre_check_mt         BOOLEAN NOT NULL DEFAULT FALSE,
  pre_check_programme  BOOLEAN NOT NULL DEFAULT FALSE,
  created_at           TIMESTAMPTZ DEFAULT NOW(),
  updated_at           TIMESTAMPTZ DEFAULT NOW()
);

-- Auto-generate ticket ID: IBT-YYMM-NNN
CREATE OR REPLACE FUNCTION generate_ticket_id()
RETURNS TRIGGER AS $$
DECLARE
  prefix TEXT;
  seq    INTEGER;
BEGIN
  prefix := 'IBT-' || TO_CHAR(NOW(), 'YYMM') || '-';
  SELECT COUNT(*) + 1 INTO seq FROM tickets WHERE id LIKE prefix || '%';
  NEW.id := prefix || LPAD(seq::TEXT, 3, '0');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tickets_generate_id
  BEFORE INSERT ON tickets
  FOR EACH ROW WHEN (NEW.id IS NULL OR NEW.id = '')
  EXECUTE FUNCTION generate_ticket_id();

-- Auto-update updated_at
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN NEW.updated_at = NOW(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tickets_updated_at
  BEFORE UPDATE ON tickets
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();


